const kamuMaliKaynak = (draft, ad) => {
  const st = draft.sourceTruth ?? {};
  const urls = st.sourceUrls ?? (st.sourceUrl ? [st.sourceUrl] : []);
  return { hakDurumu: "kamu-mali", kaynak: { ad, tur: st.sourceType, kapsam: st.scope, url: urls[0] ?? null, urls } };
};

